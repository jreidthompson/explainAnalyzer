"""Generate a psql script that tests every actionable remedy in a rolled-back transaction.

Output directory:
  experiments.sql  run with:  psql -X -d <db> -f experiments.sql
  query.sql        the statement under test (copied from --query, or a placeholder)
  manifest.json    maps each captured plan to the remedy that produced it
  out/             captured EXPLAIN (ANALYZE, BUFFERS, SETTINGS, FORMAT JSON) plans
Then:  explain-analyzer --compare <dir>
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from .querysplit import prepare

from .remedies import Remedy

EXPLAIN = "EXPLAIN (ANALYZE, BUFFERS, SETTINGS, FORMAT JSON)"
HEADER = """\
-- Generated by explain-analyzer. Run this from the directory it lives in:
--     psql -X -d <database> -f experiments.sql
-- Every experiment runs inside BEGIN ... ROLLBACK, so DDL/SET LOCAL/ANALYZE changes are undone.
-- Steps marked NOT ROLLED BACK are routine maintenance (VACUUM) that cannot run in a transaction.
--
-- WARNING: EXPLAIN ANALYZE really executes the statement once per experiment (DML is rolled back).
-- WARNING: plain CREATE INDEX blocks writes to the table while it builds - use a staging copy or replica.
\\set ON_ERROR_STOP off
\\set QUIET on
\\pset tuples_only on
\\pset format unaligned
\\! mkdir -p out
\\set q `cat query.sql`
"""


# Settings that do not exist on older servers: the experiment is skipped there instead of failing.
VERSIONED = {"hash_mem_multiplier": "PostgreSQL 13+", "jit": "PostgreSQL 11+"}


def _needs(stmts: list[str]) -> list[str]:
    found = []
    for s in stmts:
        m = re.match(r"\s*SET\s+(?:LOCAL\s+|SESSION\s+)?([A-Za-z_][\w.]*)", s, re.I)
        if m and m.group(1).lower() in VERSIONED and m.group(1).lower() not in found:
            found.append(m.group(1).lower())
    return found


def _search_path_sql(names: list[str], schema: str | None, qualified: list[tuple[str, str]] | None = None) -> str:
    """psql statements that store the search_path to use in variable :sp (and flag ambiguous names).

    ``psql -X`` skips ~/.psqlrc, which is where many people set search_path, so tables that the plan shows
    without a schema (they were visible on the capturing session's path) would not be found. Resolve the
    schemas from the live catalog and put them in front of the current path.

    A name that exists in several schemas is ambiguous - the offline tool cannot know which one the capturing
    session meant. We pick the schema that is visible on the current path (what an unqualified reference means
    for a default session), never one the plan itself shows qualified (so an unqualified `orders` cannot be
    `archive.orders` when the plan prints `archive.orders` separately), and print a WARNING.
    """
    if schema:
        return f"SELECT concat_ws(', ', {_sql_str(_qi(schema))}, current_setting('search_path')) AS sp \\gset"
    excl = ""
    if qualified:
        pairs = ", ".join(f"({_sql_str(s)}, {_sql_str(r)})" for s, r in sorted(set(qualified)))
        excl = f" AND (n.nspname, c.relname) NOT IN ({pairs})"
    lst = ", ".join(_sql_str(n) for n in names)
    cand = ("SELECT c.relname, n.nspname, pg_table_is_visible(c.oid) AS vis FROM pg_class c "
            "JOIN pg_namespace n ON n.oid = c.relnamespace WHERE c.relname IN (" + lst + ") "
            "AND c.relkind IN ('r','p','m','v','f') AND n.nspname NOT LIKE 'pg\\_%' "
            "AND n.nspname <> 'information_schema'" + excl)
    chosen = f"(SELECT DISTINCT ON (relname) relname, nspname FROM ({cand}) x ORDER BY relname, vis DESC, nspname) y"
    amb = (f"SELECT coalesce(string_agg(relname || ' exists in: ' || s, '; '), '') AS amb FROM (SELECT relname, "
           f"string_agg(nspname, ', ' ORDER BY nspname) AS s, count(*) AS k FROM ({cand}) x GROUP BY relname) z WHERE k > 1")
    return (
        "SELECT concat_ws(', ', (SELECT string_agg(DISTINCT quote_ident(nspname), ', ') FROM " + chosen + "), "
        "current_setting('search_path')) AS sp \\gset\n"
        f"SELECT (amb <> '') AS has_amb, amb FROM ({amb}) w \\gset\n"
        "\\if :has_amb\n"
        "\\echo WARNING: ambiguous table name(s): :amb\n"
        "\\echo WARNING: the script chose the schema visible on search_path (else the alphabetically first). If that is\n"
        "\\echo WARNING: not the one you analyzed, re-run with --schema NAME or put SET search_path = ...; in query.sql.\n"
        "\\endif")


def _qi(name: str) -> str:
    from .remedies import qi
    return qi(name)


def _block(name: str, file: str, stmts: list[str], preamble: bool = False, use_sp: bool = False) -> str:
    body = "\n".join(stmts)
    pre = ("SET LOCAL search_path = :sp;\n" if use_sp else "") + ("\\i preamble.sql\n" if preamble else "")
    run = f"{pre}{body}\n\\o {file}\n{EXPLAIN} :q\n;\n\\o\n"
    need = _needs(stmts)
    if need:   # only run where every versioned setting exists
        skip = "; ".join(f"{n} needs {VERSIONED[n]}" for n in need)
        opens = "".join(f"\\if :has_{n}\n" for n in need)           # psql \if takes one value: nest them
        closes = "".join("\\else\n" f"\\echo     skipped: {skip}\n\\endif\n" for _ in need)
        run = f"{opens}{run}{closes}"
    return f"\\echo >>> {name}\nBEGIN;\n{run}ROLLBACK;\n"


def _sql_str(v) -> str:
    return "'" + str(v).replace("'", "''") + "'"


def generate(remedies: list[Remedy], outdir: str | Path, query_file: str | None = None,
             source: str = "", settings: dict | None = None, relations: list[str] | None = None,
             schema: str | None = None, qualified: list[tuple[str, str]] | None = None,
             fingerprint: dict | None = None) -> dict:
    out = Path(outdir)
    (out / "out").mkdir(parents=True, exist_ok=True)
    notes: list[str] = []
    pre: list[str] = []
    set_names: set[str] = set()
    if query_file:
        q = prepare(Path(query_file).read_text(encoding="utf-8"))
        (out / "query.sql").write_text(q["main"] + "\n", encoding="utf-8")
        pre, notes, set_names = q["preamble"], q["notes"], q["set_names"]
    elif not (out / "query.sql").exists():
        (out / "query.sql").write_text("-- put the statement under test here (plain SQL, no EXPLAIN, no $1 parameters)\n",
                                       encoding="utf-8")
    # replay the non-default settings the plan was captured under (EXPLAIN SETTINGS), unless the query file sets them
    # set_config(..., true) == SET LOCAL, but it parses list-valued settings (search_path = 'a, public') correctly
    # and needs no quoting care; SET LOCAL name = 'a, public' would treat the list as ONE schema name.
    plan_items = [(k, v) for k, v in (settings or {}).items()
                  if re.fullmatch(r"[A-Za-z_][\w.]*", str(k)) and str(k).lower() not in set_names]
    plan_sets = []
    if plan_items:
        calls = " ".join(f"PERFORM set_config({_sql_str(k)}, {_sql_str(v)}, true);" for k, v in plan_items)
        plan_sets = [f"DO $ea$ BEGIN {calls} END $ea$;"]
        notes.append(f"replaying {len(plan_items)} non-default setting(s) recorded in the plan: "
                     + ", ".join(k for k, _ in plan_items))
    preamble_sql = [*(s.rstrip(";") + ";" for s in pre), *plan_sets]
    has_pre = bool(preamble_sql)
    if has_pre:
        (out / "preamble.sql").write_text(
            "-- Replayed at the start of every experiment transaction (after BEGIN).\n"
            "-- Statements from your query file, then settings recorded in the plan.\n"
            + "\n".join(preamble_sql) + "\n", encoding="utf-8")
    elif (out / "preamble.sql").exists():
        (out / "preamble.sql").unlink()

    use_sp = bool(schema or relations)
    sp_line = (_search_path_sql(sorted(set(relations or [])), schema, qualified) + "\n") if use_sp else ""
    if use_sp:
        notes.append(("tables are placed in schema " + schema) if schema else
                     "the plan has no schema for " + ", ".join(sorted(set(relations or []))[:6])
                     + ("..." if len(set(relations or [])) > 6 else "")
                     + ": the script looks their schemas up in the database at run time and puts them on search_path "
                       "(a name that exists in several schemas is ambiguous: pass --schema NAME, and check the compare output's "
                       "baseline-reproduction warning)")
    parts = [HEADER.replace("\\set q `cat query.sql`\n",
                            "\\set q `cat query.sql`\n" + sp_line +
                            "SELECT (current_setting('hash_mem_multiplier', true) IS NOT NULL) AS has_hash_mem_multiplier \\gset\n"
                            "SELECT (current_setting('jit', true) IS NOT NULL) AS has_jit \\gset\n")]
    manifest = {"source_plan": source, "baseline": "out/baseline.json", "experiments": [], "skipped": [],
                "notes": notes, "fingerprint": fingerprint or {}}
    parts.append("-- warm-up run (result discarded): warms the cache so later runs are comparable\n")
    parts.append(_block("warm-up", "out/warmup.json", ["-- (no changes)"], has_pre, use_sp))
    parts.append(_block("baseline", "out/baseline.json", ["-- (no changes)"], has_pre, use_sp))

    combo: list[str] = []
    for r in remedies:
        if r.manual or r.diagnostic_only and not r.try_variants or not r.try_variants:
            manifest["skipped"].append({"id": r.id, "title": r.title,
                                        "reason": "manual change" if r.manual else "nothing to run"})
            continue
        for i, (label, stmts) in enumerate(r.try_variants, 1):
            fname = f"out/{r.id}_{i}.json"
            title = f"{r.id} {r.title} [{label}]"
            if not r.transactional:
                sp_on, sp_off = ("SET search_path = :sp;\n", "\nRESET search_path;") if use_sp else ("", "")
                parts.append(f"\\echo >>> {r.id}: NOT ROLLED BACK (maintenance)\n{sp_on}" + "\n".join(stmts) + sp_off + "\n")
                parts.append(_block(f"{title} (after maintenance)", fname, ["-- (maintenance applied above)"], has_pre, use_sp))
            else:
                parts.append(_block(title, fname, stmts, has_pre, use_sp))
            manifest["experiments"].append({
                "id": f"{r.id}_{i}", "remedy": r.id, "title": r.title, "variant": label, "file": fname,
                "kind": r.kind, "stage": r.stage, "apply": r.apply, "diagnostic_only": r.diagnostic_only,
                "transactional": r.transactional})
        if r.transactional and not r.diagnostic_only and r.kind in ("index", "statistics", "maintenance") \
                and r.try_variants:
            combo.extend(r.try_variants[0][1])
    structural = [r for r in remedies if r.transactional and not r.diagnostic_only
                  and r.kind in ("index", "statistics", "maintenance") and r.try_variants]
    if len(structural) >= 2:
        parts.append(_block("COMBINED: all index/statistics/ANALYZE actions together", "out/combined.json", combo, has_pre, use_sp))
        manifest["experiments"].append({
            "id": "combined", "remedy": ",".join(r.id for r in structural),
            "title": "All index/statistics/ANALYZE actions together", "variant": "combined",
            "file": "out/combined.json", "kind": "combined", "stage": 2,
            "apply": list(dict.fromkeys(s for r in structural for s in r.apply)), "diagnostic_only": False, "transactional": True})
    parts.append("\\echo >>> done. Now run:  python -m explain_analyzer --compare .\n")
    (out / "experiments.sql").write_text("\n".join(parts), encoding="utf-8")
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest
